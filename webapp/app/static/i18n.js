let LANG = "en";

function detectLang() {
  try {
    const saved = localStorage.getItem("tg_lang");
    if (saved && I18N[saved]) return saved;
  } catch (_e) { /* storage unavailable */ }
  const nav = (typeof navigator !== "undefined" && navigator.language) ? navigator.language : "en";
  const base = nav.toLowerCase().split("-")[0];
  if (I18N[base]) return base;
  return "en";
}

function getLang() { return LANG; }

function t(key, params) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (params) {
    for (const k of Object.keys(params)) {
      s = s.split("{" + k + "}").join(String(params[k]));
    }
  }
  return s;
}

function _fill(s, arr) {
  let out = s;
  for (let i = 0; i < arr.length; i++) {
    out = out.split("{" + (i + 1) + "}").join(arr[i]);
  }
  return out;
}

function translateServer(str) {
  if (!str || LANG === "en") return str;
  const key = SERVER_EXACT[str];
  if (key) return t(key);
  for (let i = 0; i < SERVER_PATTERNS.length; i++) {
    const m = str.match(SERVER_PATTERNS[i][0]);
    if (m) {
      let k = SERVER_PATTERNS[i][1];
      if (k === "srv.__fail") k = m[1] === "1" ? "srv.fail_one" : "srv.fail_many";
      return _fill(t(k), m.slice(1));
    }
  }
  return str;
}

function applyStaticI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

function setLang(lang) {
  if (!I18N[lang]) lang = "en";
  LANG = lang;
  try { localStorage.setItem("tg_lang", lang); } catch (_e) { /* storage unavailable */ }
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  document.documentElement.dir = I18N_RTL.indexOf(lang) >= 0 ? "rtl" : "ltr";
  const sel = document.getElementById && document.getElementById("langSelect");
  if (sel && sel.value !== lang) sel.value = lang;
  applyStaticI18n(document);
  return LANG;
}

/* apply the detected language as soon as the markup above is parsed */
